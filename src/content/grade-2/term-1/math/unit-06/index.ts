import { buildMathUnit } from '../buildMathUnit';
import { calculate, choose, chooseNumber, makeTask, pair, q8, sortInto } from '../questionAuthoring';

const times = (left: number, right: number) => calculate(
  `每组有${right}个，${left}组一共有多少个？`, `${left} × ${right}`, left * right,
  `用${right}的乘法口诀数${left}组。`, `${left}乘${right}等于${left * right}。`,
);

export const unit = buildMathUnit({
  formalUnitNumber: 6,
  title: '第六单元 · 表内乘法（二）',
  sourceTopics: ['练习7、8、9的乘法口诀', '用乘法口诀解决分组和简单数量问题'],
  basicTasks: [
    makeTask('7、8、9口诀训练场', '练习7、8、9的乘法口诀并解释乘法表示的分组。', 'companion-03', q8([
      times(7, 2), times(7, 4), times(8, 3), times(8, 5),
      times(9, 2), times(9, 4),
      chooseNumber('8排座位，每排9个位置，一共有多少个？', 72, [63, 81], '用8个9相加。', '8乘9等于72个位置。'),
      pair('把口诀算式和得数配起来。', [['7 × 8', '56'], ['8 × 9', '72'], ['9 × 6', '54']], '按口诀逐个计算。', '7乘8得56，8乘9得72，9乘6得54。'),
    ])),
    makeTask('乘法问题解码站', '从分组情境中找出组数和每组数量，再用口诀求总数。', 'companion-01', q8([
      chooseNumber('7个盒子里每个放8颗珠子，一共有多少颗？', 56, [49, 64], '一共有7组，每组8颗。', '7乘8等于56颗。'),
      chooseNumber('9辆小车每辆有4个轮子，共有多少个轮子？', 36, [32, 40], '数一数有几辆车，每辆几个轮子。', '9乘4等于36个轮子。'),
      times(8, 7), times(9, 8),
      pair('把数量情境和算式配起来。', [['8队，每队7人', '8 × 7'], ['9盘，每盘6个', '9 × 6'], ['7排，每排9盆', '7 × 9']], '组数和每组数量分别是一个因数。', '用组数乘每组数量表示总数。'),
      sortInto('把情境分到“可以直接用乘法”或“数量还不同”。', ['可以直接用乘法', '数量还不同'], [
        { label: '8袋，每袋9个球', categoryIndex: 0 }, { label: '一袋7个红球和8个蓝球', categoryIndex: 1 },
        { label: '9组，每组7张卡', categoryIndex: 0 }, { label: '桌上有8支笔和3本书', categoryIndex: 1 },
      ], '看每组的数量是不是相同。', '同样数量的重复分组可以用乘法求总数。'),
      choose('一道乘法题的因数是9和7，怎样理解？', ['9组，每组7个', '9比7多2', '7组减去9个'], 0, '乘法可以表示相同数量的组。', '9乘7表示9组，每组7个。'),
      times(7, 7),
    ])),
  ],
  advancedTask: makeTask('乘法规律与验算挑战', '熟练运用口诀，比较交换因数后的乘积并检查分组结果。', 'companion-02', q8([
    times(7, 9), times(9, 7), times(8, 6), times(6, 8),
    chooseNumber('7×8和8×7的积相差多少？', 0, [1, 15], '先分别用口诀求积。', '两道算式的积都是56，相差0。'),
    pair('把算式和结果配起来。', [['7 × 6', '42'], ['8 × 8', '64'], ['9 × 5', '45']], '每一题都能用乘法口诀求积。', '三个乘积分别是42、64和45。'),
    sortInto('把算式分到“积是72”或“积不是72”。', ['积是72', '积不是72'], [
      { label: '8 × 9', categoryIndex: 0 }, { label: '9 × 7', categoryIndex: 1 },
      { label: '9 × 8', categoryIndex: 0 }, { label: '8 × 8', categoryIndex: 1 },
    ], '使用口诀计算后再分类。', '8乘9和9乘8的积都是72。'),
    choose('8组，每组9个，可以怎样写算式？', ['8 × 9', '8 + 9', '9 - 8'], 0, '组数写在前面，每组数量写在后面。', '8组、每组9个写成8乘9。'),
  ])),
  highTask: makeTask('星际物资分组规划', '用7、8、9的口诀规划物资分组，解释总数并检查遗漏。', 'companion-04', q8([
    chooseNumber('8名伙伴每人领取7枚徽章，需要多少枚？', 56, [48, 63], '用8个7相加。', '8乘7等于56枚。'),
    chooseNumber('9个机器人每个装8个轮子，共需多少个？', 72, [64, 81], '用9组、每组8个计算。', '9乘8等于72个轮子。'),
    times(7, 8), times(8, 9),
    pair('把规划问题和对应算式配起来。', [['7箱，每箱9件', '7 × 9'], ['8队，每队6人', '8 × 6'], ['9排，每排8盆', '9 × 8']], '找出组数和每组的数量。', '每个情境都用组数乘每组数量。'),
    sortInto('把检查方式分到“查组数”或“查每组数量”。', ['查组数', '查每组数量'], [
      { label: '数清有几排', categoryIndex: 0 }, { label: '确认每排放几个', categoryIndex: 1 },
      { label: '检查盒子一共有几只', categoryIndex: 0 }, { label: '核对每只盒子里的卡片数', categoryIndex: 1 },
    ], '总数由组数和每组数量共同决定。', '两个因数都核实，分组计算才不容易漏掉。'),
    choose('计算7×8后，怎样检查是否少数了一组？', ['确认7组都各有8个', '只看答案是不是偶数', '把8写成7'], 0, '回到题目检查每个因数的意思。', '核对组数和每组数量能检查列式是否完整。'),
    chooseNumber('7个箱子每个装9个零件，一共装了多少个？', 63, [56, 72], '用7乘9。', '7乘9等于63个零件。'),
  ])),
});
